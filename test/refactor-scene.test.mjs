function recordingContext(trace = []) {
  return new Proxy({}, {
    set(target, key, value) { trace.push(['set', key, value]); target[key] = value; return true; },
    get(target, key) { return target[key] ?? ((...args) => trace.push([key, ...args])); },
  });
}

