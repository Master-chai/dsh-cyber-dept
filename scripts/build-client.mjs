import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {dirname,resolve} from 'node:path';
import {build} from 'esbuild';

const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const check=process.argv.includes('--check');
// React stays external: the factory receives the DSH-provided instance.
// Local sprites and CSS remain embedded; no runtime CDN or chunk requests.
for(const [entry,target] of [['src/client/index.js','client.js'],['src/client/testing.js','.verify/client-test.js']]) {
  const result=await build({absWorkingDir:root,entryPoints:[entry],bundle:true,write:false,format:'cjs',platform:'browser',target:'es2022',external:['react'],loader:{'.png':'dataurl','.css':'text'},charset:'utf8',legalComments:'inline',metafile:true});
  const code='// Generated by npm run build. Edit src/client modules, not this file.\n'+
    'window.__ModuleLoader__.load({id:"dsh-cyber-dept",factory:(require)=>{\nvar module={exports:{}};\n'+result.outputFiles[0].text+'\nreturn module.exports;\n}});\n';
  const path=resolve(root,target);
  if(check&&target==='client.js') {
    if(readFileSync(path,'utf8')!==code)throw new Error('client.js is stale; run npm run build');
    console.log('client.js matches module sources.');
  } else {
    mkdirSync(dirname(path),{recursive:true});writeFileSync(path,code);
    console.log(`Built ${target} (${Buffer.byteLength(code)} bytes).`);
  }
  if(!check&&target==='client.js'){
    mkdirSync(resolve(root,'.verify'),{recursive:true});
    writeFileSync(resolve(root,'.verify/build-meta.json'),JSON.stringify(result.metafile,null,2));
  }
}
